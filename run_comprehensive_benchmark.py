"""
Run Comprehensive Benchmark on Trained Dirac Point Neural Network

This script executes the comprehensive benchmark suite generated by
comprehensive_benchmark_design.py and produces detailed performance reports.

The benchmark includes (CORRECTED Nov 27, 2025):
- 50 training sample tests (exact training data - baseline performance)
- 50 weight interpolation tests (weights between training min/max)
- 50 weight extrapolation tests (weights above training max)
- 50 threshold extrapolation tests (thresholds above training max)
- 30 scaling invariance tests (scale factors [10,20])
- 40 coprime extrapolation - close (new coprime a∈[11,15])
- 20 coprime extrapolation - far (new coprime a∈[16,20])
- 10 redundancy pairs (20 tests - scale-equivalent systems)

Total: ~300 parameter sets

REFACTORED ARCHITECTURE:
- comprehensive_benchmark_executor: Test execution and results collection
- comprehensive_benchmark_analyzer: Results analysis and statistics
- comprehensive_benchmark_reporter: Report generation and output
"""

import constants
from constants import logging, os
from constants import Dict, Any
from comprehensive_benchmark_executor import comprehensive_benchmark_executor
from comprehensive_benchmark_analyzer import comprehensive_benchmark_analyzer
from comprehensive_benchmark_reporter import comprehensive_benchmark_reporter

# Configure logging
logger = logging.getLogger(__name__)


def run_comprehensive_benchmark(model_path: str = "final_trained_model.npz",
                                output_prefix: str = "baseline",
                                num_iterations: int = constants.BENCHMARK_NUM_ITERATIONS) -> Dict[str, Any]:
    """
    Run comprehensive benchmark on a trained model.

    This function can be called from other scripts (e.g., NN_Dirac_point.py) to run
    the full benchmark suite and save results.

    Args:
        model_path: Path to trained model weights (relative to constants.PATH)
        output_prefix: Prefix for output files (e.g., 'baseline', 'physics_trained')
        num_iterations: Number of timing iterations per parameter set

    Returns:
        Dict with summary statistics, or dict with 'error' key if failed
    """
    logger.info("=" * 80)
    logger.info("COMPREHENSIVE BENCHMARK EXECUTION")
    logger.info("=" * 80)
    logger.info(f"Model: {model_path}")
    logger.info(f"Output prefix: {output_prefix}")

    # Create benchmark modules
    executor = comprehensive_benchmark_executor(
        model_path=model_path,
        benchmark_suite_path=os.path.join(constants.PATH, "benchmark_test_suite.json")
    )
    analyzer = comprehensive_benchmark_analyzer()
    reporter = comprehensive_benchmark_reporter()

    # Run full benchmark
    logger.info("\nStarting benchmark execution...\n")
    results = executor.run_full_benchmark(num_iterations=num_iterations)

    if 'error' in results:
        logger.error(f"Benchmark failed: {results['error']}")
        return results

    # Save raw results
    logger.info("\nSaving results...")
    results_json = os.path.join(constants.PATH, f"{output_prefix}_benchmark_results.json")
    reporter.save_results(results, results_json)

    # Generate and display summary
    logger.info("\nGenerating summary report...")
    summary = analyzer.generate_summary_report(results)

    # Save summary JSON
    summary_json = os.path.join(constants.PATH, f"{output_prefix}_benchmark_summary.json")
    reporter.save_results(summary, summary_json)

    # Save summary TXT
    summary_txt = os.path.join(constants.PATH, f"{output_prefix}_benchmark_summary.txt")
    reporter.save_summary_txt(summary, summary_txt)

    # Print summary to console
    reporter.print_summary(summary)

    logger.info("\n" + "=" * 80)
    logger.info("BENCHMARK COMPLETE")
    logger.info("=" * 80)
    logger.info("\nResults saved to:")
    logger.info(f"  - {output_prefix}_benchmark_results.json (full results)")
    logger.info(f"  - {output_prefix}_benchmark_summary.json (summary statistics)")
    logger.info(f"  - {output_prefix}_benchmark_summary.txt (human-readable summary)")

    return summary


def main():
    """Run comprehensive benchmark on default trained model."""

    # Run with default parameters
    run_comprehensive_benchmark(
        model_path="final_trained_model.npz",
        output_prefix="baseline"
    )


if __name__ == "__main__":
    main()
